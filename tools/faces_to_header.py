"""Convert face drawings into a C header for the mask firmware.

Usage:
    python tools/faces_to_header.py OUT.h NAME=drawing.png [NAME=drawing.png ...]

Each drawing is one panel side at any size with a 2:1 aspect (e.g. 1888x944), black background.
Orientation: draw the side shown on the RIGHT-hand panel, with the centre of the mask (nose) on
the left of the drawing and the outer edge on the right. The firmware mirrors it for the other panel.

Colours:
  - white / grey strokes -> "tint": coloured live by the mask's colour mode (DOWN button, plasma)
  - anything coloured     -> drawn in that fixed colour (e.g. a pink eye, red blush)

Downsampling is by area coverage, so strokes thinner than one LED still show up.

For each NAME the header defines:
  FACE_<NAME>_TINT[256]         64x32 1-bit XBM, MSB first (right-hand panel orientation)
  FACE_<NAME>_TINT_MIRROR[256]  the same, mirrored for the left-hand panel
  FACE_<NAME>_COLOUR[2048]      64x32 RGB565 fixed colours, 0 = no fixed colour (right-hand orientation)
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image

W, H = 64, 32
LIT_THRESHOLD = 0.3      # a source pixel counts as "drawn" if its brightest channel is above this
COVERAGE_THRESHOLD = 0.12  # an LED lights if this fraction of its area is drawn
TINT_MIN_CHANNEL = 0.78  # all channels above this (white/near-white) -> tint


def convert(path: Path):
    img = Image.open(path).convert("RGB")
    sw, sh = img.size
    if abs(sw / sh - 2.0) > 0.05:
        raise SystemExit(f"{path}: expected a 2:1 image, got {sw}x{sh}")
    a = np.asarray(img).astype(np.float32) / 255.0
    bh, bw = sh / H, sw / W
    tint = np.zeros((H, W), dtype=bool)
    colour = np.zeros((H, W), dtype=np.uint16)
    for y in range(H):
        for x in range(W):
            blk = a[int(y * bh):int((y + 1) * bh), int(x * bw):int((x + 1) * bw)]
            lit = blk.max(axis=2) > LIT_THRESHOLD
            if lit.mean() <= COVERAGE_THRESHOLD:
                continue
            r, g, b = blk[lit].mean(axis=0)
            if min(r, g, b) >= TINT_MIN_CHANNEL:
                tint[y, x] = True
            else:
                v = ((int(r * 255) & 0xF8) << 8) | ((int(g * 255) & 0xFC) << 3) | (int(b * 255) >> 3)
                colour[y, x] = v or 1  # 0 means "none"
    return tint, colour


def xbm_bytes(mask):
    out = []
    for row in mask:
        for byte in range(W // 8):
            v = 0
            for bit in range(8):
                if row[byte * 8 + bit]:
                    v |= 0x80 >> bit
            out.append(v)
    return out


def c_array(ctype, name, values, per_line):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"0x{v:02X}" if ctype == "uint8_t" else f"0x{v:04X}"
                                         for v in values[i:i + per_line]) + ",")
    return f"static const {ctype} {name}[{len(values)}] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out = Path(sys.argv[1])
    parts = [f"// Generated by tools/faces_to_header.py - do not edit by hand.\n#pragma once\n#include <stdint.h>\n"
             f"#include <pgmspace.h>\n#define CUSTOM_FACES_WIDTH {W}\n#define CUSTOM_FACES_HEIGHT {H}\n"]
    for arg in sys.argv[2:]:
        name, _, src = arg.partition("=")
        tint, colour = convert(Path(src))
        n = name.upper()
        parts.append(c_array("uint8_t", f"FACE_{n}_TINT", xbm_bytes(tint), 16))
        parts.append(c_array("uint8_t", f"FACE_{n}_TINT_MIRROR", xbm_bytes(tint[:, ::-1]), 16))
        parts.append(c_array("uint16_t", f"FACE_{n}_COLOUR", colour.flatten().tolist(), 16))
        print(f"{name}: {int(tint.sum())} tint LEDs, {int((colour > 0).sum())} fixed-colour LEDs")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
